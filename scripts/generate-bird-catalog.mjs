import { readFile, writeFile } from "node:fs/promises";

const [sourcePath = "/tmp/aos-birds.csv", outputPath = "data/bird-catalog.ts", whitelistPath = "data/bird-whitelist.ts"] = process.argv.slice(2);

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") { row.push(field); field = ""; }
    else if (char === "\n") { row.push(field.replace(/\r$/, "")); rows.push(row); row = []; field = ""; }
    else field += char;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const headers = rows.shift();
  return rows.map((values) => Object.fromEntries(headers.map((header, i) => [header, values[i] ?? ""])));
}

function slugify(name) {
  return name.toLowerCase().replace(/[’']/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const csv = await readFile(sourcePath, "utf8");
const rows = parseCsv(csv)
  .filter((row) => row.rank === "species" && row.common_name && row.species && !row.status_extinct)
  .map((row) => ({
    slug: slugify(row.common_name),
    commonName: row.common_name,
    scientificName: row.species,
    order: row.order || "Aves",
    family: row.family || "Aves",
    introduced: Boolean(row.status_introduced),
    nonbreeding: Boolean(row.status_nonbreeding),
    accidental: Boolean(row.status_accidental),
    sourceId: Number(row.id),
  }));

const whitelistSource = await readFile(whitelistPath, "utf8");
const priorityNames = [...whitelistSource.matchAll(/\["([^"]+)",\s*"([^"]+)"\]/g)].map((match) => match[1]);
const prioritySet = new Set(priorityNames);
const prioritizedRows = [
  ...priorityNames.map((name) => rows.find((row) => row.commonName === name)).filter(Boolean),
  ...rows.filter((row) => !prioritySet.has(row.commonName)),
];

const unique = [];
const slugs = new Set();
for (const bird of prioritizedRows) {
  if (!bird.slug || slugs.has(bird.slug)) continue;
  slugs.add(bird.slug);
  unique.push(bird);
  if (unique.length === 1000) break;
}

if (unique.length !== 1000) throw new Error(`Expected 1000 unique species, found ${unique.length}`);

const header = `/**\n * First 1,000 living species from the American Ornithological Society's\n * North and Middle American Checklist (downloaded 2026-08-11).\n * Source: https://checklist.americanornithology.org/taxa/\n * Generated by scripts/generate-bird-catalog.mjs — do not edit by hand.\n */\n\n`;
const types = `export type CatalogBird = {\n  slug: string; commonName: string; scientificName: string; order: string; family: string;\n  introduced: boolean; nonbreeding: boolean; accidental: boolean; sourceId: number;\n};\n\n`;
await writeFile(outputPath, `${header}${types}export const birdCatalog: CatalogBird[] = ${JSON.stringify(unique, null, 2)};\n`);
console.log(`Wrote ${unique.length} species to ${outputPath}`);
